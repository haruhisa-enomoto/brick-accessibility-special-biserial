#!/usr/bin/env python3
"""Generate the standalone Challenge from the maintained Mathlib-only statement."""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
THEOREM = """
universe u

/-- **Theorem A** (Theorem 5.4). Over a basic finite-dimensional brick-finite special
biserial algebra over an algebraically closed field, every nonsimple brick has a brick
submodule or a brick quotient of dimension one less. -/
theorem BrickAccessibility.Challenge.theoremA : BrickAccessibility.Statement.TheoremA.{u} := by
  sorry

/-- **Corollary B** (Corollary 5.5). Every brick over such an algebra is brick accessible,
and the brick dimensions of a nonzero such algebra form an interval `{1, …, N}`. -/
theorem BrickAccessibility.Challenge.corollaryB : BrickAccessibility.Statement.CorollaryB.{u} := by
  sorry

/-- **Corollary 5.6.** The conclusions of Theorem A and Corollary B hold for basic
representation-finite biserial algebras. -/
theorem BrickAccessibility.Challenge.corollaryBiserial :
    BrickAccessibility.Statement.CorollaryBiserial.{u} := by
  sorry
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if Challenge.lean is stale")
    args = parser.parse_args()
    source = (ROOT / "BrickAccessibility/Statement.lean").read_text()
    imports = [line.split()[-1] for line in source.splitlines()
               if line.startswith(("import ", "public import "))]
    if not imports or any(name != "Mathlib" and not name.startswith("Mathlib.") for name in imports):
        raise SystemExit("Statement.lean must import only Mathlib")
    expected = "-- Generated by scripts/generate_challenge.py; edit Statement.lean.\n" + source + THEOREM
    target = ROOT / "Challenge.lean"
    if args.check:
        if not target.exists() or target.read_text() != expected:
            raise SystemExit("Challenge.lean is stale; run scripts/generate_challenge.py")
    else:
        target.write_text(expected)
    print(f"Challenge.lean: {len(expected.splitlines())} lines, {len(expected.encode())} bytes")


if __name__ == "__main__":
    main()
